#!/usr/bin/env bash
# Wasignal one-command installer for a small Debian/Ubuntu VPS.
#
#   curl -fsSL https://raw.githubusercontent.com/digitaldominationio/wasignal/main/install.sh | sudo bash
#
# Optional overrides (put them before `sudo bash`):
#   DOMAIN=app.example.com ADMIN_PHONE=919999000001 ADMIN_OTP=123456
#
# Commands: install (default) | update | status | logs | backup | uninstall
set -euo pipefail

REPO_RAW="${WASIGNAL_RAW:-https://raw.githubusercontent.com/digitaldominationio/wasignal/main}"
REPO_GIT="${WASIGNAL_GIT:-https://github.com/digitaldominationio/wasignal.git}"
INSTALL_DIR="${WASIGNAL_DIR:-/opt/wasignal}"
IMAGE="${WASIGNAL_IMAGE:-ghcr.io/digitaldominationio/wasignal:latest}"
COMMAND="${1:-install}"

log()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!!\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31mERR\033[0m %s\n' "$*" >&2; exit 1; }

need_root() {
  [ "$(id -u)" -eq 0 ] || die "run as root: curl ... | sudo bash"
}

rand_hex() { openssl rand -hex "${1:-16}"; }
rand_otp() {
  local n
  n=$((16#$(openssl rand -hex 3) % 900000 + 100000))
  printf '%06d' "$n"
}

detect_ip() {
  curl -4 -fsS --max-time 5 https://api.ipify.org 2>/dev/null \
    || hostname -I 2>/dev/null | awk '{print $1}' \
    || echo "127.0.0.1"
}

install_packages() {
  log "Installing base packages"
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq ca-certificates curl openssl git ufw >/dev/null
}

install_docker() {
  if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    log "Docker already installed"
  else
    log "Installing Docker Engine + Compose"
    curl -fsSL https://get.docker.com | sh
  fi
  if command -v systemctl >/dev/null 2>&1; then
    systemctl enable --now docker >/dev/null 2>&1 || true
  fi
  docker compose version >/dev/null 2>&1 || die "docker compose plugin missing"
}

ensure_swap() {
  local mem_mb
  mem_mb=$(awk '/MemTotal/{print int($2/1024)}' /proc/meminfo)
  if [ "$mem_mb" -ge 1500 ]; then
    return
  fi
  if swapon --show 2>/dev/null | grep -q .; then
    log "Swap already present"
    return
  fi
  log "Adding 2G swap (server has ${mem_mb}MB RAM)"
  if ! fallocate -l 2G /swapfile 2>/dev/null; then
    dd if=/dev/zero of=/swapfile bs=1M count=2048 status=none
  fi
  chmod 600 /swapfile
  mkswap /swapfile >/dev/null
  swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
}

configure_firewall() {
  command -v ufw >/dev/null 2>&1 || return
  if ufw status 2>/dev/null | grep -qi "Status: active"; then
    log "Allowing 22/80/443 through ufw"
    ufw allow 22/tcp >/dev/null 2>&1 || true
    ufw allow 80/tcp >/dev/null 2>&1 || true
    ufw allow 443/tcp >/dev/null 2>&1 || true
    ufw allow 443/udp >/dev/null 2>&1 || true
  else
    warn "ufw is inactive; leaving firewall untouched (Docker publishes 80/443)."
  fi
}

fetch_file() {
  local name="$1" dest="$2"
  if [ -f "$dest" ]; then
    return
  fi
  curl -fsSL "$REPO_RAW/deploy/installer/$name" -o "$dest"
}

write_env() {
  local env_file="$INSTALL_DIR/.env"
  if [ -f "$env_file" ]; then
    log "Keeping existing .env (secrets preserved)"
    return
  fi

  local domain="${DOMAIN:-}"
  if [ -z "$domain" ] && [ -t 0 ]; then
    read -rp "Domain (leave blank to use the server IP over HTTP): " domain || true
  fi
  local admin_phone="${ADMIN_PHONE:-}"
  if [ -z "$admin_phone" ] && [ -t 0 ]; then
    read -rp "Admin WhatsApp number (digits, e.g. 919999000001): " admin_phone || true
  fi
  admin_phone="${admin_phone:-9999000001}"
  local otp="${ADMIN_OTP:-$(rand_otp)}"
  local ip; ip="$(detect_ip)"

  local site_address public_url cookie_secure
  if [ -n "$domain" ]; then
    site_address="$domain"
    public_url="https://$domain"
    cookie_secure="true"
  else
    site_address=":80"
    public_url="http://$ip"
    cookie_secure="false"
  fi

  umask 077
  cat > "$env_file" <<EOF
# Generated by install.sh — keep this file private.
DOMAIN=$domain
SITE_ADDRESS=$site_address
PUBLIC_URL=$public_url
WASIGNAL_IMAGE=$IMAGE
WASIGNAL_COOKIE_SECURE=$cookie_secure

MONGO_PASSWORD=$(rand_hex 16)
REDIS_PASSWORD=$(rand_hex 16)
WASIGNAL_SECRET_KEY=$(rand_hex 32)
WASIGNAL_INTERNAL_KEY=$(rand_hex 24)

ADMIN_PHONE=$admin_phone
ADMIN_OTP=$otp
EOF
  chmod 600 "$env_file"
  log "Wrote $env_file"
}

pull_or_build() {
  cd "$INSTALL_DIR"
  # shellcheck disable=SC1091
  set -a; . ./.env; set +a

  log "Pulling images"
  if ! docker compose pull --quiet app 2>/dev/null; then
    warn "Image pull failed; building from source (slower, needs ~2GB swap)"
    rm -rf "$INSTALL_DIR/src"
    git clone --depth 1 "$REPO_GIT" "$INSTALL_DIR/src"
    docker build -f "$INSTALL_DIR/src/Dockerfile.allinone" -t wasignal:local "$INSTALL_DIR/src"
    sed -i 's|^WASIGNAL_IMAGE=.*|WASIGNAL_IMAGE=wasignal:local|' .env
  fi
  docker compose pull --quiet mongo redis caddy 2>/dev/null || true
}

wait_healthy() {
  cd "$INSTALL_DIR"
  log "Waiting for the API to become healthy"
  for _ in $(seq 1 60); do
    if docker compose exec -T app curl -fsS http://127.0.0.1/api/health/live >/dev/null 2>&1; then
      return 0
    fi
    sleep 3
  done
  warn "API did not report healthy in time. Recent logs:"
  docker compose logs --tail=40 app || true
  return 1
}

install_cron() {
  cat > /etc/cron.d/wasignal-backup <<EOF
30 2 * * * root $INSTALL_DIR/install.sh backup >> /var/log/wasignal-backup.log 2>&1
EOF
  chmod 644 /etc/cron.d/wasignal-backup
}

summary() {
  # shellcheck disable=SC1091
  set -a; . "$INSTALL_DIR/.env"; set +a
  printf '\033[1;32mWasignal is running.\033[0m\n\n'
  cat <<EOF
  URL        ${PUBLIC_URL}
  Login      phone ${ADMIN_PHONE}
  OTP        ${ADMIN_OTP}        (change WASIGNAL_DEV_OTP in $INSTALL_DIR/.env after setup)
  Admin      ${PUBLIC_URL}/dashboard/admin

  Directory  ${INSTALL_DIR}
  Logs       cd ${INSTALL_DIR} && docker compose logs -f app
  Status     ${INSTALL_DIR}/install.sh status
  Update     ${INSTALL_DIR}/install.sh update
  Backup     ${INSTALL_DIR}/install.sh backup
  Restore    see docs/INSTALL.md

  Point DNS at this server before using a domain; Caddy retries the certificate.
  First boot seeds one workspace and marks this phone as superadmin.
EOF
}

do_install() {
  need_root
  log "Installing Wasignal into $INSTALL_DIR"
  [ -f /etc/os-release ] || die "unsupported OS (Debian/Ubuntu expected)"
  # shellcheck disable=SC1091
  . /etc/os-release
  case "${ID:-}" in
    ubuntu|debian) ;;
    *) warn "Untested distribution: ${ID:-unknown}" ;;
  esac

  install_packages
  install_docker
  ensure_swap

  mkdir -p "$INSTALL_DIR"
  fetch_file docker-compose.yml "$INSTALL_DIR/docker-compose.yml"
  fetch_file Caddyfile "$INSTALL_DIR/Caddyfile"
  curl -fsSL "$REPO_RAW/install.sh" -o "$INSTALL_DIR/install.sh"
  chmod +x "$INSTALL_DIR/install.sh"

  write_env
  configure_firewall
  pull_or_build

  cd "$INSTALL_DIR"
  docker compose up -d --remove-orphans
  wait_healthy || die "startup failed; check: cd $INSTALL_DIR && docker compose logs"
  install_cron
  summary
}

load_env() {
  [ -f "$INSTALL_DIR/.env" ] || die "not installed at $INSTALL_DIR"
  # shellcheck disable=SC1091
  set -a; . "$INSTALL_DIR/.env"; set +a
}

do_update() {
  need_root
  load_env
  cd "$INSTALL_DIR"
  log "Updating Wasignal"
  if [ "${WASIGNAL_IMAGE}" = "wasignal:local" ]; then
    rm -rf "$INSTALL_DIR/src"
    git clone --depth 1 "$REPO_GIT" "$INSTALL_DIR/src"
    docker build -f "$INSTALL_DIR/src/Dockerfile.allinone" -t wasignal:local "$INSTALL_DIR/src"
  else
    docker compose pull --quiet app
  fi
  curl -fsSL "$REPO_RAW/deploy/installer/docker-compose.yml" -o "$INSTALL_DIR/docker-compose.yml"
  curl -fsSL "$REPO_RAW/deploy/installer/Caddyfile" -o "$INSTALL_DIR/Caddyfile"
  docker compose up -d --remove-orphans
  wait_healthy
  docker image prune -f >/dev/null 2>&1 || true
  log "Updated"
}

do_status() {
  load_env
  cd "$INSTALL_DIR"
  docker compose ps
  printf '\nHealth: '
  docker compose exec -T app curl -fsS http://127.0.0.1/api/health/ready || true
  printf '\nURL: %s\n' "${PUBLIC_URL}"
}

do_logs() {
  load_env
  cd "$INSTALL_DIR"
  docker compose logs -f --tail=200 app
}

do_backup() {
  need_root
  load_env
  cd "$INSTALL_DIR"
  local dir="/var/backups/wasignal"
  mkdir -p "$dir"
  local stamp; stamp=$(date +%Y%m%d-%H%M%S)
  log "Writing $dir/mongo-$stamp.gz"
  docker compose exec -T mongo mongodump \
    --archive --gzip \
    --username wasignal --password "$MONGO_PASSWORD" --authenticationDatabase admin \
    > "$dir/mongo-$stamp.gz"
  find "$dir" -name 'mongo-*.gz' -mtime +7 -delete
  log "Backup done ($(du -h "$dir/mongo-$stamp.gz" | cut -f1))"
}

do_uninstall() {
  need_root
  load_env
  cd "$INSTALL_DIR"
  local purge="${1:-}"
  log "Stopping Wasignal"
  docker compose down --remove-orphans
  rm -f /etc/cron.d/wasignal-backup
  if [ "$purge" = "--purge" ]; then
    warn "Removing volumes (data will be lost)"
    docker compose down -v --remove-orphans
    rm -rf "$INSTALL_DIR"
    log "Purged"
  else
    log "Stopped. Add --purge to delete data and $INSTALL_DIR"
  fi
}

case "$COMMAND" in
  install)   do_install ;;
  update)    do_update ;;
  status)    do_status ;;
  logs)      do_logs ;;
  backup)    do_backup ;;
  uninstall) do_uninstall "${2:-}" ;;
  -h|--help|help)
    sed -n '2,12p' "$0" ;;
  *) die "unknown command: $COMMAND" ;;
esac
